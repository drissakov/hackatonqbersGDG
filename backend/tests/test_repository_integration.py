@pytest.fixture
def repository():
    url = os.environ.get("TEST_DATABASE_URL", "")
    if not url:
        pytest.skip("not_run: TEST_DATABASE_URL absent; DATABASE_URL is never used by tests")
    pool = DatabasePool(url)
    schema = "test_s01_" + uuid4().hex[:12]
    try:
        assert migrate(pool, schema)
        yield PostgresPOIRepository(pool, schema=schema, allow_test=True)
    finally:
        # The exact schema was generated by this fixture; no user schema is removed.
        schema_name(schema)
        assert schema.startswith("test_s01_")
        try:
            with pool.connection() as connection:
                connection.execute(
                    sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(schema))
                )
        finally:
            pool.close()


def record(index="one", *, is_test=True):
    path = Path(__file__).resolve().parents[2] / "contracts/examples/poi.test.json"
    row = json.loads(path.read_text(encoding="utf-8"))
    row.update(id=f"synthetic:{index}", external_id=index, is_test=is_test)
    row["sources"][0].update(is_test=is_test, provider="test_fixture" if is_test else "other")
    row["provenance"][0]["external_id"] = index
    return row


def upsert(repo, rows):
    return asyncio.run(repo.upsert_pois(rows))


def stored(repo):
    with repo.pool.connection() as connection:
        return connection.execute(
            sql.SQL("SELECT * FROM {} ORDER BY id").format(repo.table("pois"))
        ).fetchall()


def test_migration_replay_tls_actual_extension_schemas_and_srid(repository):
    repo = repository
    assert not migrate(repo.pool, repo.schema)
    upsert(repo, [record()])
    with repo.pool.connection() as connection:
        extensions = repo.extension_schemas(connection)
        assert set(extensions) == {"postgis", "vector", "pg_trgm"}
        # Behind Supavisor, pg_stat_ssl describes pooler -> database, not our
        # client -> pooler connection. Verify libpq's actual client TLS state.
        assert connection.pgconn.ssl_in_use
        geo = sql.Identifier(extensions["postgis"])
        row = connection.execute(
            sql.SQL("SELECT {}.ST_SRID(location::{}.geometry) AS srid FROM {}").format(
                geo, geo, repo.table("pois")
            )
        ).fetchone()
        assert row["srid"] == 4326


def test_upsert_identity_preserves_canonical_id_and_partial_import_keeps_other_rows(repository):
    repo = repository
    result = upsert(repo, [record("one"), record("two")])
    assert (result.inserted, result.updated, result.rejected) == (2, 0, 0)
    changed = record("one")
    changed.update(id="new-proposed-id", name="Synthetic updated name")
    result = upsert(repo, [changed])
    assert (result.inserted, result.updated) == (0, 1)
    rows = stored(repo)
    assert len(rows) == 2
    assert rows[0]["id"] == "synthetic:one"
    assert rows[0]["document"]["id"] == "synthetic:one"
    assert rows[0]["document"]["name"] == "Synthetic updated name"


def test_batch_counts_duplicates_invalid_rights_and_id_collision(repository):
    first = record()
    denied = record("denied")
    denied["sources"][0].update(storage_allowed=False, indexing_allowed=False)
    collision = record("collision")
    collision["id"] = first["id"]
    result = upsert(repository, [first, copy.deepcopy(first), {}, denied, collision])
    assert result.inserted + result.updated + result.rejected == 5
    assert result.inserted == 1
    assert [(r.index, r.code) for r in result.rejections] == [
        (1, "duplicate_in_batch"),
        (2, "invalid_record"),
        (3, "storage_not_permitted"),
        (4, "invalid_record"),
    ]


def test_invalid_text_does_not_abort_other_records_in_the_batch(repository):
    invalid = record("invalid")
    invalid["description"] = "Synthetic NUL\x00from an external source"
    result = upsert(repository, [record("one"), invalid, record("two")])
    assert (result.inserted, result.updated, result.rejected) == (2, 0, 1)
    assert [(r.index, r.code) for r in result.rejections] == [(1, "invalid_record")]
    assert len(stored(repository)) == 2


def test_stale_matching_observation_and_unknown_times_are_transactional(repository):
    row = record()
    row["provenance"][0]["observed_at"] = None
    assert upsert(repository, [row]).inserted == 1
    assert upsert(repository, [row]).updated == 1
    known = record()
    assert upsert(repository, [known]).updated == 1
    old = record()
    old["provenance"][0]["observed_at"] = "2020-01-01T00:00:00Z"
    for rejected in [old, row]:
        result = upsert(repository, [rejected])
        assert result.rejections[0].code == "stale_record"
    assert upsert(repository, [known]).updated == 1
    assert stored(repository)[0]["primary_observed_at"].year == 2030


def test_infrastructure_failure_rolls_back_all_accepted_records(repository, monkeypatch):
    original = repository._write

    def failing_write(connection, extensions, item, canonical_id, exists):
        original(connection, extensions, item, canonical_id, exists)
        if item.identity[1] == "two":
            raise psycopg.OperationalError("synthetic failure after writing second row")

    monkeypatch.setattr(repository, "_write", failing_write)
    with pytest.raises(DatabaseUnavailable):
        upsert(repository, [record("one"), record("two")])
    assert stored(repository) == []
    with repository.pool.connection() as connection:
        runs = connection.execute(
            sql.SQL("SELECT * FROM {}").format(repository.table("import_runs"))
        ).fetchall()
        assert len(runs) == 1 and runs[0]["status"] == "failed"


def test_concurrent_upserts_share_one_identity(repository):
    async def run():
        return await asyncio.gather(
            repository.upsert_pois([record()]), repository.upsert_pois([record()])
        )

    results = asyncio.run(run())
    assert sum(r.inserted for r in results) == 1
    assert sum(r.updated for r in results) == 1
    assert len(stored(repository)) == 1


def test_coverage_and_geo_exclude_tests_by_default_and_do_not_claim_city_coverage(repository):
    upsert(repository, [record("real-shape", is_test=False), record("test")])
    missing = record("missing", is_test=False)
    missing["location"] = None
    upsert(repository, [missing])
    production = PostgresPOIRepository(repository.pool, schema=repository.schema)
    coverage = asyncio.run(production.coverage())
    assert coverage["production_pois"] == 2
    assert coverage["test_pois"] == 1
    assert coverage["located_pois"] == 1
    assert coverage["missing_location_pois"] == 1
    assert coverage["city_coverage"] == "unknown"
    origin = Coordinates(latitude=51.128, longitude=71.43)
    assert len(asyncio.run(production.geo_search(origin, 100, 10))) == 1
    assert len(asyncio.run(repository.geo_search(origin, 100, 10))) == 2
    far = Coordinates(latitude=0, longitude=0)
    assert asyncio.run(repository.geo_search(far, 100, 10)) == []


