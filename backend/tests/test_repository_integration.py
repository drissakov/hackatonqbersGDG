        indexes = connection.execute(
            "SELECT indexdef FROM pg_indexes WHERE schemaname=%s "
            "AND indexname IN ('pois_text_idx','pois_location_idx')",
            (repository.schema,),
        ).fetchall()
        assert len(indexes) == 2
        assert all("WHERE indexing_allowed" in row["indexdef"] for row in indexes)
