"""Real TLS PostgreSQL checks, ONLY with TEST_DATABASE_URL and generated schemas.

No DATABASE_URL fallback. All records are synthetic, including production-shaped
rows used to test counters. Extensions are installed if absent, never relocated
or dropped. Run only against a disposable test database with DDL permissions.
"""

