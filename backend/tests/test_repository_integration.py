def add_embedding(repo, *, dimensions=1536):
    with repo.pool.connection() as connection:
        vec = sql.Identifier(repo.extension_schemas(connection)["vector"])
        connection.execute(
            sql.SQL(
                "INSERT INTO {} (poi_id,indexed_text_hash,model,dimensions,embedding) "
                "SELECT id,indexed_text_hash,'synthetic-test-model',%s,%s::{}.vector(1536) FROM {}"
            ).format(repo.table("embeddings"), vec, repo.table("pois")),
            (dimensions, json.dumps([1.0] + [0.0] * 1535)),
        )


def test_embedding_metadata_operator_and_hash_invalidation(repository):
    row = record()
    upsert(repository, [row])
    add_embedding(repository)
    with repository.pool.connection() as connection:
        vec = sql.Identifier(repository.extension_schemas(connection)["vector"])
        distance = connection.execute(
            sql.SQL("SELECT embedding OPERATOR({}.<=>) embedding AS distance FROM {}").format(
                vec, repository.table("embeddings")
            )
        ).fetchone()["distance"]
        assert distance == 0
        assert (
            connection.execute(
                sql.SQL("SELECT embedding <=> embedding AS distance FROM {}").format(
                    repository.table("embeddings")
                )
            ).fetchone()["distance"]
            == 0
        )
    upsert(repository, [row])
    with repository.pool.connection() as connection:
        assert (
            connection.execute(
                sql.SQL("SELECT count(*) AS n FROM {}").format(repository.table("embeddings"))
            ).fetchone()["n"]
            == 1
        )
    row["description"] = "Changed synthetic source text"
    upsert(repository, [row])
    with repository.pool.connection() as connection:
        assert (
            connection.execute(
                sql.SQL("SELECT count(*) AS n FROM {}").format(repository.table("embeddings"))
            ).fetchone()["n"]
            == 0
        )


